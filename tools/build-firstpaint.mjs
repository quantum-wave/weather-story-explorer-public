#!/usr/bin/env node
// Writes site/js/ui/firstpaint-geo.js: the Regional view's coastline and graticule pre-projected at scale 1, translate 0, for the first
// paint before d3 arrives (site/js/ui/firstpaint.js, W3-05). Uses the renderer's own projection (render/view.js baseProjection) and coastline
// mesh (render/basemap.js coastMesh on geo/countries-110m.json), so it draws the same lines the renderer will draw.
//
//   node tools/build-firstpaint.mjs           write the file
//   node tools/build-firstpaint.mjs --check   exit 1 if the file is stale, or if firstpaint.js's fit differs from baseProjection's
//
// The check is also run by tests/site/checks/S-STATUS.mjs.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SITE = path.join(ROOT, 'site');
const OUT = path.join(SITE, 'js', 'ui', 'firstpaint-geo.js');
const imp = (rel) => import(pathToFileURL(path.join(SITE, rel)).href);

const SCALE = 1000; // d3 resamples at this scale (0.5 px), about the phone's and the desktop's real scales
const Q = 5000; // stored in units of 2e-4: 0.2 px at scale 1000 (the real scales are about 650 on desktop and 1000 on the phone)
const SF = [-122.42, 37.77];

/** The encoded geometry, as a string of JavaScript. */
export async function build() {
  const { d3 } = await imp('js/vendor.js');
  const { baseProjection } = await imp('js/render/view.js');
  const { coastMesh } = await imp('js/render/basemap.js');
  const topo = JSON.parse(fs.readFileSync(path.join(SITE, 'geo', 'countries-110m.json'), 'utf8'));
  const proj = baseProjection('np', 1000, 600).proj.scale(SCALE).translate([0, 0]);
  const u = (ll) => proj(ll).map((v) => v / SCALE);

  // what any canvas shape can show at the default zoom: the landscape box widened by a quarter of its width each side (a 2.4:1 screen shows 19 %) and 15 % of its height
  const boxPts = [];
  for (let x = -200; x <= -60; x += 4) boxPts.push([x, 15], [x, 72]);
  for (let y = 15; y <= 72; y += 4) boxPts.push([-200, y], [-60, y]);
  const bbox = (pts) => { const p = pts.map(u); return [Math.min(...p.map((q) => q[0])), Math.min(...p.map((q) => q[1])), Math.max(...p.map((q) => q[0])), Math.max(...p.map((q) => q[1]))]; };
  const land = bbox(boxPts), port = bbox([[SF[0], 22], [SF[0], 60]]);
  const pw = land[2] - land[0], ph = land[3] - land[1];
  const keep = [land[0] - 0.25 * pw, land[1] - 0.15 * ph, land[2] + 0.25 * pw, land[3] + 0.15 * ph];
  const inside = (x, y) => x >= keep[0] && x <= keep[2] && y >= keep[1] && y <= keep[3];

  const lines = (obj) => {
    const out = []; let cur = null;
    const flush = () => { if (cur && cur.length >= 4) out.push(cur); cur = null; };
    let px = null, py = null, pin = false;
    const ctx = {
      moveTo(x, y) { flush(); px = x / SCALE; py = y / SCALE; pin = inside(px, py); cur = pin ? [px, py] : null; },
      lineTo(x, y) {
        x /= SCALE; y /= SCALE; const now = inside(x, y);
        if (now || pin) { if (!cur) cur = [px, py]; cur.push(x, y); } // keep one point beyond the box at each end, so lines reach the edge
        else flush();
        px = x; py = y; pin = now;
      },
      closePath() {}, arc() {}, beginPath() {},
    };
    d3.geoPath(proj, ctx)(obj);
    flush();
    return out;
  };
  const enc = (ls) => ls.map((p) => {
    let x = 0, y = 0; const v = [];
    for (let i = 0; i < p.length; i += 2) { const qx = Math.round(p[i] * Q), qy = Math.round(p[i + 1] * Q); v.push(qx - x, qy - y); x = qx; y = qy; }
    return v.join(',');
  }).join(';');
  const coast = lines(coastMesh(topo));
  const grat = lines(d3.geoGraticule().step([30, 30])());
  const r6 = (a) => a.map((v) => +v.toFixed(9));
  return `// Generated by tools/build-firstpaint.mjs from geo/countries-110m.json with render/view.js's Regional projection. Do not edit.
// Unit positions (scale 1, translate 0) of the Regional view: the fit boxes (landscape and portrait), San Francisco, 150W 60N, and the 110 m
// coastline and 30-degree graticule (${coast.length} and ${grat.length} lines), delta-coded in units of 1/q.
export const GEO = {
  q: ${Q},
  land: ${JSON.stringify(r6(land))},
  port: ${JSON.stringify(r6(port))},
  sf: ${JSON.stringify(r6(u(SF)))},
  anchor: ${JSON.stringify(r6(u([-150, 60])))},
  coast: '${enc(coast)}',
  graticule: '${enc(grat)}',
};
`;
}

/** firstpaint.js's fit against baseProjection's for phone and desktop shapes, insets included: the largest gap in px at four places. */
export async function fitGap() {
  const { baseProjection } = await imp('js/render/view.js');
  const { fitRegional } = await imp('js/ui/firstpaint.js');
  const unit = baseProjection('np', 1000, 600).proj.scale(1).translate([0, 0]);
  let worst = 0;
  for (const [W, H, inset] of [[1440, 900, {}], [1024, 768, {}], [2560, 1080, {}], [390, 844, { top: 56, bottom: 301 }], [390, 844, {}], [360, 640, { top: 56, bottom: 301 }], [1440, 760, {}], [800, 1200, {}]]) {
    const p = baseProjection('np', W, H, { top: 0, right: 0, bottom: 0, left: 0, ...inset }).proj;
    const f = fitRegional(W, H, inset);
    for (const ll of [SF, [-150, 60], [-100, 20], [170, 50]]) {
      const a = p(ll), u = unit(ll);
      worst = Math.max(worst, Math.hypot(a[0] - (f.tx + f.k * u[0]), a[1] - (f.ty + f.k * u[1])));
    }
  }
  return worst;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const text = await build();
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    const gap = await fitGap();
    console.log(`firstpaint-geo.js ${cur === text ? 'up to date' : 'STALE'}; fit gap ${gap.toExponential(2)} px`);
    process.exit(cur === text && gap < 0.01 ? 0 : 1);
  }
  fs.writeFileSync(OUT, text);
  console.log(`wrote ${path.relative(ROOT, OUT)}: ${text.length} bytes`);
}
